#!/usr/bin/env node
'use strict';

const { isSea, getAsset } = require('node:sea');
const path = require('node:path');
const fs = require('node:fs');

const VERSION = '1.0.0';

/**
 * Resolve the path to the bundled Chrome binary.
 *
 * Distribution layout (next to the SEA binary):
 *   dist/
 *     myBinary          (or myBinary.exe)
 *     chrome/
 *       chrome          (Linux/macOS) or chrome.exe (Windows)
 *       ... (full Chrome for Testing tree)
 *
 * The binary looks relative to its own location (process.execPath)
 * so it works regardless of the current working directory.
 */
function getChromeExecutablePath() {
  const binDir = path.dirname(process.execPath);
  const chromeDir = path.join(binDir, 'chrome');

  const candidates = [
    path.join(chromeDir, 'chrome'),
    path.join(chromeDir, 'chrome.exe'),
    path.join(chromeDir, 'chrome-linux64', 'chrome'),
    path.join(chromeDir, 'chrome-mac-arm64', 'Google Chrome for Testing.app', 'Contents', 'MacOS', 'Google Chrome for Testing'),
    path.join(chromeDir, 'chrome-mac-x64', 'Google Chrome for Testing.app', 'Contents', 'MacOS', 'Google Chrome for Testing'),
    path.join(chromeDir, 'chrome-win64', 'chrome.exe'),
  ];

  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) {
      return candidate;
    }
  }

  // Fallback: environment override (useful in CI or local dev)
  if (process.env.PUPPETEER_EXECUTABLE_PATH) {
    return process.env.PUPPETEER_EXECUTABLE_PATH;
  }

  return null;
}

function showHelp() {
  console.log(`
myBinary v${VERSION} — Node.js SEA CLI with Puppeteer PDF rendering

Usage:
  myBinary [name]
  myBinary pdf [output.pdf]
  myBinary --help
  myBinary --version
  myBinary --asset

Options:
  --help, -h      Show this help
  --version, -v   Show version
  --asset         Display embedded asset content
  pdf [file]      Generate a sample PDF using bundled Chrome (default: output.pdf)

Chrome is expected next to this binary in a 'chrome/' folder.
Set PUPPETEER_EXECUTABLE_PATH to override.
`);
}

async function generatePdf(outputPath) {
  let puppeteer;
  try {
    puppeteer = require('puppeteer-core');
  } catch (err) {
    console.error('Puppeteer is not available. Rebuild the binary after installing dependencies.');
    process.exit(1);
  }

  const executablePath = getChromeExecutablePath();
  if (!executablePath) {
    console.error('Bundled Chrome not found next to the binary.');
    console.error('Expected layout: <binary-dir>/chrome/chrome (or platform equivalent)');
    console.error('Or set PUPPETEER_EXECUTABLE_PATH.');
    process.exit(1);
  }

  console.log(`Using Chrome at: ${executablePath}`);

  const browser = await puppeteer.launch({
    executablePath,
    headless: true,
    args: [
      '--no-sandbox',
      '--disable-setuid-sandbox',
      '--disable-dev-shm-usage',
      '--disable-gpu',
    ],
  });

  try {
    const page = await browser.newPage();
    await page.setContent(`
      <!DOCTYPE html>
      <html>
        <head><meta charset="utf-8"><title>SEA PDF</title></head>
        <body style="font-family: sans-serif; padding: 40px;">
          <h1>Generated by myBinary</h1>
          <p>This PDF was rendered with Puppeteer using a Chrome binary bundled next to the SEA executable.</p>
          <p>Generated at: ${new Date().toISOString()}</p>
          <p>Running as SEA: ${isSea()}</p>
        </body>
      </html>
    `);

    const pdfBuffer = await page.pdf({
      format: 'A4',
      printBackground: true,
    });

    fs.writeFileSync(outputPath, pdfBuffer);
    console.log(`PDF written to: ${outputPath}`);
  } finally {
    await browser.close();
  }
}

async function main() {
  const args = process.argv.slice(2);

  if (args.includes('--help') || args.includes('-h') || args.length === 0) {
    showHelp();
    process.exit(0);
  }

  if (args.includes('--version') || args.includes('-v')) {
    console.log(`myBinary v${VERSION}`);
    process.exit(0);
  }

  if (args.includes('--asset')) {
    if (isSea()) {
      const asset = getAsset('greeting.txt');
      const text = Buffer.from(asset).toString('utf8');
      console.log('Embedded asset content:');
      console.log(text);
    } else {
      console.log('Not running as SEA — asset embedding is only available in the binary.');
    }
    process.exit(0);
  }

  if (args[0] === 'pdf') {
    const output = args[1] || 'output.pdf';
    await generatePdf(output);
    process.exit(0);
  }

  const name = args[0] || 'World';
  console.log(`Hello, ${name}!`);

  if (isSea()) {
    console.log('(Running as a Single Executable Application)');
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
